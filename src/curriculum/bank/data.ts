/* The big kindergarten knowledge bank: everything a child walking into first grade
   meets in readiness workbooks — animals, the body, jobs, food, weather, holidays, safety,
   opposites, riddles and more. Every item pairs words with a picture, for a child who can't read yet. */

import type { Pic } from '../kdata'

const P = (list: string): Pic[] => list.trim().split(/\s*,\s*/).map((x) => { const i = x.lastIndexOf(' '); return { w: x.slice(0, i), e: x.slice(i + 1) } })
/** [picture, name] pairs written as "name emoji → name emoji". */
const PAIRS = (list: string): [Pic, Pic][] => list.trim().split(/\s*\n\s*/).map((line) => { const [a, b] = line.split('→').map((x) => P(x)[0]); return [a, b] })

