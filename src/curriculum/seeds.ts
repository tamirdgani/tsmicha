/* The years after pre-K. Each is 12 chapters × 8 lessons (plus a check, a review and a challenge per chapter),
   and each is a clear step harder than the one before:
   · Kindergarten: letters and calculating from the very first lesson — the whole alef-bet, adding and
     taking away to 10 and then 20, first words and sentences.
   · First grade: reading with niqqud, final letters, sentences and short stories; math to 100.
   · Second grade: grammar and reading comprehension; carrying and borrowing, times, sharing, to 1000. */

