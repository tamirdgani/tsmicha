/* The kindergarten word and picture bank. Every item pairs a word with an emoji,
   so a child who can't read yet still knows what's on the card. */

export type Pic = { w: string; e: string }
const P = (list: string): Pic[] => list.trim().split(/\s*,\s*/).map((x) => { const [w, e] = x.split(' '); return { w, e } })

