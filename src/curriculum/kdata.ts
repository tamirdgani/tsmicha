/** Letters that sound alike at the start of a word. Never offered side by side as answers. */
export const SOUND_ALIKE = ['אע', 'בו', 'חכ', 'טת', 'כק', 'סש']
export const alike = (a: string, b: string) => a === b || SOUND_ALIKE.some((g) => g.includes(a) && g.includes(b))

